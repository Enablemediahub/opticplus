CREATE TABLE IF NOT EXISTS `customer_followups` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `branch_id` INT UNSIGNED NOT NULL,
  `billing_id` BIGINT UNSIGNED NOT NULL,
  `patient_id` BIGINT UNSIGNED NULL,
  `folder_id` VARCHAR(60) NULL,
  `pickup_at` TIMESTAMP NOT NULL,
  `milestone` VARCHAR(32) NOT NULL,
  `due_at` DATE NOT NULL,
  `status` VARCHAR(24) NOT NULL DEFAULT 'pending',
  `attempt_count` SMALLINT UNSIGNED NOT NULL DEFAULT 0,
  `last_attempt_at` TIMESTAMP NULL,
  `next_attempt_at` TIMESTAMP NULL,
  `completed_by` BIGINT UNSIGNED NULL,
  `completed_at` TIMESTAMP NULL,
  `complaint_status` VARCHAR(24) NOT NULL DEFAULT 'none',
  `complaint_resolution_notes` TEXT NULL,
  `complaint_resolved_by` BIGINT UNSIGNED NULL,
  `complaint_resolved_at` TIMESTAMP NULL,
  `created_by` BIGINT UNSIGNED NULL,
  `created_at` TIMESTAMP NULL,
  `updated_at` TIMESTAMP NULL,
  PRIMARY KEY (`id`),
  UNIQUE KEY `customer_followups_billing_milestone_unique` (`billing_id`, `milestone`),
  KEY `customer_followups_branch_queue_index` (`branch_id`, `status`, `due_at`),
  KEY `customer_followups_branch_complaints_index` (`branch_id`, `complaint_status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS `customer_followup_attempts` (
  `id` BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  `followup_id` BIGINT UNSIGNED NOT NULL,
  `attempted_by` BIGINT UNSIGNED NOT NULL,
  `attempted_at` TIMESTAMP NOT NULL,
  `contact_result` VARCHAR(32) NOT NULL,
  `wearing_frequency` VARCHAR(24) NULL,
  `vision_response` VARCHAR(24) NULL,
  `complaint_category` VARCHAR(40) NOT NULL DEFAULT 'none',
  `complaint_notes` TEXT NULL,
  `needs_optometrist_review` TINYINT(1) NOT NULL DEFAULT 0,
  `next_attempt_at` TIMESTAMP NULL,
  `call_notes` TEXT NULL,
  `created_at` TIMESTAMP NULL,
  `updated_at` TIMESTAMP NULL,
  PRIMARY KEY (`id`),
  KEY `customer_followup_attempts_staff_date_index` (`attempted_by`, `attempted_at`),
  KEY `customer_followup_attempts_history_index` (`followup_id`, `attempted_at`),
  CONSTRAINT `customer_followup_attempts_followup_id_foreign`
    FOREIGN KEY (`followup_id`) REFERENCES `customer_followups` (`id`) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
